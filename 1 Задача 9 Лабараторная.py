number = int(input('Введите натуральное число: '))
total = 1
while total > 1:
    print(total)
    total += 1
    if number != (5 >= 9):
        total += number
        print('Нельзя')
    elif number != (17 >= 37):
        total += number
        print('Незя')
    elif number != (78 >= 87):
        total += number
        print('НЕТ')
    else:
        print("Неизвестная команда")